import numpy as np # importation de la bibliothèque NumPy
tabl1=np.arange(0,100,7) # création d'un tableau NumPy avec des valeurs de 0 à 100 avec un pas de 7
print(tabl1) # affichage du tableau
tabl2=np.arange(51,151,2) # création d'un deuxième tableau NumPy avec des valeurs de 51 à 150 avec un pas de 2
print(tabl2) # affichage du deuxième tableau
tabl3=np.linspace(-5,5,20) # création d'un troisième tableau NumPy avec 20 valeurs uniformément réparties entre -5 et 5
print(tabl3) # affichage du troisième tableau